#[derive(sqlx::FromRow)]
struct NameRow {
    name: String,
}
#[derive(sqlx::FromRow)]
struct IdRow {
    #[sqlx(rename = "operation_id!")]
    operation_id: String,
}
#[derive(sqlx::FromRow)]
struct CounterRow {
    #[sqlx(rename = "value!: i64")]
    value: i64,
}
#[derive(sqlx::FromRow)]
struct ReceiptRow {
    #[sqlx(rename = "request!: i64")]
    request: i64,
    #[sqlx(rename = "answer!: i64")]
    answer: i64,
}
#[derive(serde::Serialize, serde::Deserialize)]
struct CallEnvelope {
    call: CallId,
    request: i64,
}

async fn read(executor: &DoTransaction, name: &str) -> Result<u64, StoreError> {
    let row = query_as::<Do, CounterRow>(include_str!(
        "../../../../crates/durable-steps/tests/conformance/queries/read_counter.sql"
    ))
    .bind(name)
    .fetch_optional(executor)
    .await?;
    u64::try_from(row.map_or(0, |row| row.value)).map_err(StoreError::backend)
}
async fn write(executor: &DoTransaction, name: &str, value: u64) -> Result<(), StoreError> {
    query::<Do>(include_str!(
        "../../../../crates/durable-steps/tests/conformance/queries/write_counter.sql"
    ))
    .bind(name)
    .bind(i64::try_from(value).map_err(StoreError::backend)?)
    .execute(executor)
    .await?;
    Ok(())
}
async fn increment(executor: &DoTransaction, name: &str) -> Result<u64, StoreError> {
    let value = read(executor, name)
        .await?
        .checked_add(1)
        .ok_or_else(|| StoreError::backend("fixture counter overflow"))?;
    write(executor, name, value).await?;
    Ok(value)
}
async fn bootstrap(executor: &DoTransaction) -> Result<(), StoreError> {
    let tables = query_as::<Do, NameRow>(
        "SELECT name FROM sqlite_master WHERE name = 'conformance_counters'",
    )
    .fetch_all(executor)
    .await?;
    if tables.is_empty() {
        executor
            .execute(include_str!(
                "../../../../crates/durable-steps/tests/conformance/migrations/1000_business.sql"
            ))
            .await?;
        executor
            .execute(include_str!(
                "../../../../crates/durable-steps/tests/conformance/migrations/1001_receiver.sql"
            ))
            .await?;
    } else if !tables.iter().all(|row| row.name == "conformance_counters") {
        return Err(StoreError::backend("unexpected fixture schema"));
    }
    Ok(())
}
impl<H: Host> JourneyScope for DurableObjectScope<'_, H> {
    async fn increment_effect(&mut self, name: &str) -> Result<u64, StoreError> {
        increment(self.executor(), name).await
    }
}
struct DoHost {
    alarm: AlarmOwner,
    receiver: ObjectNamespace,
    receiver_name: String,
    entropy: [u8; 10],
    next: AtomicU64,
}
impl Clock for DoHost {
    fn now(&self) -> SyncTime {
        SyncTime::from_unix_millis(
            i64::try_from(worker::Date::now().as_millis()).unwrap_or(i64::MAX),
        )
    }
}
impl IdSource for DoHost {
    fn new_id(&self) -> Uuid {
        let [c0, c1, c2, c3, c4, c5, c6, c7] =
            self.next.fetch_add(1, Ordering::SeqCst).to_be_bytes();
        let [e0, e1, e2, e3, e4, e5, e6, e7, e8, e9] = self.entropy;
        // A seeded fixture UUIDv7 stream, independent of the controlled suite's
        // clock/IDs. Its namespace is generated by the journey controller.
        uuid::Builder::from_unix_timestamp_millis(
            worker::Date::now().as_millis(),
            &[
                e0,
                e1,
                e2 ^ c0,
                e3 ^ c1,
                e4 ^ c2,
                e5 ^ c3,
                e6 ^ c4,
                e7 ^ c5,
                e8 ^ c6,
                e9 ^ c7,
            ],
        )
        .into_uuid()
    }
}
impl WakeScheduler for DoHost {
    async fn wake_at(&self, at: SyncTime) -> Result<(), WakeFailure> {
        self.alarm.wake_at(at).await
    }
}
impl Host for DoHost {
    fn dispatch<C: CallTarget>(
        &self,
        _target: C,
        request: C::Request,
        call: CallId,
    ) -> impl std::future::Future<Output = Result<C::Answer, CallFailure>> + Send {
        SendFuture::new(async move {
            let request: i64 = serde_json::from_slice(&serde_json::to_vec(&request).map_err(lost)?)
                .map_err(lost)?;
            let body = serde_json::to_string(&CallEnvelope { call, request }).map_err(lost)?;
            let mut init = RequestInit::new();
            init.with_method(Method::Post).with_body(Some(body.into()));
            let request =
                Request::new_with_init("https://receiver.local/call", &init).map_err(lost)?;
            let mut response = self
                .receiver
                .id_from_name(&self.receiver_name)
                .map_err(lost)?
                .get_stub()
                .map_err(lost)?
                .fetch_with_request(request)
                .await
                .map_err(lost)?;
            if response.status_code() != 200 {
                return Err(CallFailure::AnswerLost);
            }
            response.json::<C::Answer>().await.map_err(lost)
        })
    }
}
fn lost(_error: impl std::fmt::Display) -> CallFailure {
    CallFailure::AnswerLost
}
struct JourneyState {
    store: Arc<DurableObjectStore<DoHost>>,
    host: Arc<DoHost>,
}
impl JourneyState {
    fn new(state: &State, env: &Env) -> worker::Result<Self> {
        let alarm = AlarmOwner::new(state.storage());
        let entropy =
            serde_json::from_str(&env.var("JOURNEY_ENTROPY")?.to_string()).map_err(worker_error)?;
        let host = Arc::new(DoHost {
            alarm: alarm.clone(),
            receiver: env.durable_object("RECEIVER")?,
            receiver_name: env.var("JOURNEY_OBJECT_NAME")?.to_string(),
            entropy,
            next: AtomicU64::new(1),
        });
        let store = Arc::new(DurableObjectStore::new(
            DoConnection::new(state.storage()),
            Arc::clone(&host),
            alarm,
        ));
        Ok(Self { store, host })
    }
    async fn initialize(&self) -> Result<(), StoreError> {
        self.store.migrate().await?;
        self.store
            .transaction(|scope| Box::pin(async move { bootstrap(scope.executor()).await }))
            .await
    }
    fn engine(&self) -> Result<Engine<DurableObjectStore<DoHost>, DoHost>, StoreError> {
        let mut engine = Engine::new(Arc::clone(&self.store), Arc::clone(&self.host));
        engine.register(JourneyTask::<DurableObjectStore<DoHost>>(PhantomData))?;
        Ok(engine)
    }
}

#[durable_object]
pub struct JourneyObject {
    state: State,
    journey: Result<JourneyState, String>,
}
impl DurableObject for JourneyObject {
    fn new(state: State, env: Env) -> Self {
        let journey = JourneyState::new(&state, &env).map_err(|error| error.to_string());
        Self { state, journey }
    }
    async fn fetch(&self, request: Request) -> worker::Result<Response> {
        let journey = self.journey.as_ref().map_err(worker_error)?;
        journey.initialize().await.map_err(worker_error)?;
        let engine = journey.engine().map_err(worker_error)?;
        match request.path().as_str() {
            "/journey/start" => {
                let id = engine
                    .start::<JourneyTask<DurableObjectStore<DoHost>>>(
                        &RequestKey::new("journey").map_err(worker_error)?,
                        JourneyInput {
                            value: 7,
                            not_before: journey.host.now().after(Duration::from_secs(3)),
                        },
                    )
                    .await
                    .map_err(worker_error)?;
                let status = engine.status(&id).await.map_err(worker_error)?;
                self.state.storage().sync().await?;
                Response::from_json(&status)
            }
            "/journey/inspect" => {
                let observed = journey.store.transaction(|scope| Box::pin(async move {
                    let row = query_as::<Do, IdRow>(include_str!("../../../../crates/durable-steps/tests/conformance/queries/journey_operation.sql")).fetch_one(scope.executor()).await?;
                    let id = OperationId(Uuid::parse_str(&row.operation_id).map_err(StoreError::backend)?);
                    let record = scope.operation(id).await?.ok_or(StoreError::MissingOperation { id })?;
                    Ok(JourneyObservation { completed: matches!(record.execution, OperationExecution::Completed { .. }), first: read(scope.executor(), "first").await?, last: read(scope.executor(), "last").await?, steps: scope.step_count(id).await?, alarm_runs: read(scope.executor(), "alarm-runs").await?, last_alarm_at: read(scope.executor(), "last-alarm-at").await? })
                })).await.map_err(worker_error)?;
                let mut receiver = journey
                    .host
                    .receiver
                    .id_from_name(&journey.host.receiver_name)?
                    .get_stub()?
                    .fetch_with_str("https://receiver.local/inspect")
                    .await?;
                let receiver: ReceiverObservation = receiver.json().await?;
                Response::from_json(&(observed, receiver))
            }
            _ => Response::error("unknown journey path", 404),
        }
    }
    async fn alarm(&self) -> worker::Result<Response> {
        let journey = self.journey.as_ref().map_err(worker_error)?;
        journey.initialize().await.map_err(worker_error)?;
        let now = u64::try_from(journey.host.now().unix_millis()).map_err(worker_error)?;
        journey
            .store
            .transaction(move |scope| {
                Box::pin(async move {
                    increment(scope.executor(), "alarm-runs").await?;
                    write(scope.executor(), "last-alarm-at", now).await
                })
            })
            .await
            .map_err(worker_error)?;
        // Only the platform alarm drives the restarted operation. Errors escape
        // the handler so workerd retains the alarm's retry safety net.
        journey
            .engine()
            .map_err(worker_error)?
            .drive_due()
            .await
            .map_err(worker_error)?;
        self.state.storage().sync().await?;
        Response::ok("alarm drove due operations")
    }
}
#[derive(serde::Serialize, serde::Deserialize)]
struct JourneyObservation {
    completed: bool,
    first: u64,
    last: u64,
    steps: u64,
    alarm_runs: u64,
    last_alarm_at: u64,
}
#[derive(serde::Serialize, serde::Deserialize)]
struct ReceiverObservation {
    remote: u64,
    deliveries: u64,
}

#[durable_object]
pub struct ReceiverObject {
    connection: DoConnection,
}
impl DurableObject for ReceiverObject {
    fn new(state: State, _env: Env) -> Self {
        Self {
            connection: DoConnection::new(state.storage()),
        }
    }
    async fn fetch(&self, mut request: Request) -> worker::Result<Response> {
        self.connection
            .transaction(|tx| async move { bootstrap(&tx).await })
            .await
            .map_err(worker_error)?;
        if request.path() == "/inspect" {
            let observed = self
                .connection
                .transaction(|tx| async move {
                    Ok::<_, StoreError>(ReceiverObservation {
                        remote: read(&tx, "remote").await?,
                        deliveries: read(&tx, "deliveries").await?,
                    })
                })
                .await
                .map_err(worker_error)?;
            return Response::from_json(&observed);
        }
        let CallEnvelope { call, request } = request.json().await?;
        let call = serde_json::to_string(&call).map_err(worker_error)?;
        let answer = self.connection.transaction(move |tx| async move {
            increment(&tx, "deliveries").await?;
            if let Some(row) = query_as::<Do,ReceiptRow>(include_str!("../../../../crates/durable-steps/tests/conformance/queries/receiver_receipt.sql")).bind(&call).fetch_optional(&tx).await? {
                if row.request != request { return Err(StoreError::backend("receiver content conflict")); }
                return Ok(row.answer);
            }
            let answer = request.checked_mul(2).ok_or_else(|| StoreError::backend("fixture answer overflow"))?;
            increment(&tx,"remote").await?;
            query::<Do>(include_str!("../../../../crates/durable-steps/tests/conformance/queries/insert_receipt.sql")).bind(call).bind(request).bind(answer).execute(&tx).await?;
            Ok(answer)
        }).await.map_err(worker_error)?;
        self.connection.storage().sync().await?;
        Response::from_json(&answer)
    }
}
