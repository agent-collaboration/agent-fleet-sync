use crate::{ColumnMetadata, GenerateError, QueryManifest, QueryMetadata, QueryResult};
use std::{
    collections::{BTreeMap, BTreeSet},
    io::Write,
    process::{Command, Stdio},
};

pub(crate) fn render_queries(
    manifest: &QueryManifest,
    metadata: &[QueryMetadata],
) -> Result<String, GenerateError> {
    let mut imports = BTreeSet::from([
        "arguments::IntoArguments",
        "database::Database",
        "query::query",
    ]);
    let has_rows = metadata.iter().any(|query| !query.columns.is_empty());
    let has_parameters = manifest
        .queries
        .iter()
        .any(|query| !query.parameters.is_empty());
    if has_rows {
        imports.extend([
            "column::ColumnIndex",
            "decode::Decode",
            "row::Row",
            "types::Type",
        ]);
    }
    if has_parameters {
        imports.extend(["encode::Encode", "types::Type"]);
    }
    let mut generated = format!(
        "// Generated by fleet-sync-query-gen. Edit the SQL and manifest, then regenerate.\nuse durable_steps::storage::TransactionScope;\nuse sqlx_core::{{{}}};\n",
        imports.into_iter().collect::<Vec<_>>().join(", ")
    );
    let mut row_shapes = BTreeMap::new();
    for (query, described) in manifest.queries.iter().zip(metadata) {
        let row_type = query.row.as_deref();
        if let Some(row_type) = row_type {
            let shape: Vec<_> = described
                .columns
                .iter()
                .map(|column| (column.name.clone(), column.rust_type.clone()))
                .collect();
            let already_emitted = if let Some(previous) = row_shapes.get(row_type) {
                if previous != &shape {
                    return Err(GenerateError::Manifest(format!(
                        "row {row_type} describes different column shapes"
                    )));
                }
                true
            } else {
                row_shapes.insert(row_type.to_owned(), shape);
                false
            };
            if !already_emitted {
                generated.push_str(&format!(
                    "\n#[derive(Debug)]\npub(crate) struct {row_type} {{\n"
                ));
                for column in &described.columns {
                    generated
                        .push_str(&format!("    pub {}: {},\n", column.name, column.rust_type));
                }
                generated.push_str("}\n");
            }
        }
        let return_type = match query.result {
            QueryResult::Execute => "()".into(),
            QueryResult::Exists => "bool".into(),
            QueryResult::Many => format!(
                "Vec<{}>",
                row_type.ok_or_else(|| GenerateError::Manifest("row type missing".into()))?
            ),
            QueryResult::Optional => format!(
                "Option<{}>",
                row_type.ok_or_else(|| GenerateError::Manifest("row type missing".into()))?
            ),
            QueryResult::One => row_type
                .ok_or_else(|| GenerateError::Manifest("row type missing".into()))?
                .into(),
        };
        generated.push_str(&format!(
            "pub(crate) async fn {}<S>(scope: &mut S",
            query.name
        ));
        for parameter in &query.parameters {
            generated.push_str(&format!(", {}: {}", parameter.name, parameter.rust_type()));
        }
        generated.push_str(&format!(") -> Result<{return_type}, sqlx_core::Error>\nwhere\n    S: TransactionScope,\n    <S::Database as Database>::Arguments: IntoArguments<S::Database>,\n"));
        let mut bounds = BTreeSet::new();
        for parameter in &query.parameters {
            bounds.insert(format!(
                "for<'value> {}: Type<S::Database> + Encode<'value, S::Database>",
                parameter.rust_type()
            ));
        }
        for column in &described.columns {
            bounds.insert(format!(
                "for<'value> {}: Type<S::Database> + Decode<'value, S::Database>",
                column.rust_type
            ));
        }
        if !described.columns.is_empty() {
            bounds
                .insert("for<'row> &'row str: ColumnIndex<<S::Database as Database>::Row>".into());
        }
        for bound in bounds {
            generated.push_str(&format!("    {bound},\n"));
        }
        generated.push_str(&format!("{{\n    let statement = query::<S::Database>(include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {:?})))", format!("/{}", query.sql)));
        for parameter in &query.parameters {
            generated.push_str(&format!(".bind({})", parameter.name));
        }
        generated.push_str(";\n");
        match query.result {
            QueryResult::Exists => generated
                .push_str("    Ok(statement.fetch_optional(scope.executor()).await?.is_some())\n"),
            QueryResult::Execute => {
                generated.push_str("    statement.execute(scope.executor()).await?;\n    Ok(())\n")
            }
            QueryResult::One => {
                generated.push_str(
                    "    let row = statement.fetch_one(scope.executor()).await?;\n    Ok(",
                );
                generated.push_str(&render_row(row_type, &described.columns)?);
                generated.push_str(")\n");
            }
            QueryResult::Optional => {
                generated.push_str("    let row = statement.fetch_optional(scope.executor()).await?;\n    row.as_ref().map(|row| Ok(");
                generated.push_str(&render_row(row_type, &described.columns)?);
                generated.push_str(")).transpose()\n");
            }
            QueryResult::Many => {
                generated.push_str("    let rows = statement.fetch_all(scope.executor()).await?;\n    rows.iter().map(|row| Ok(");
                generated.push_str(&render_row(row_type, &described.columns)?);
                generated.push_str(")).collect()\n");
            }
        }
        generated.push_str("}\n");
    }
    format_source(generated)
}
fn render_row(name: Option<&str>, columns: &[ColumnMetadata]) -> Result<String, GenerateError> {
    let mut row = format!(
        "{} {{\n",
        name.ok_or_else(|| GenerateError::Manifest("row type missing".into()))?
    );
    for column in columns {
        row.push_str(&format!(
            "{}: row.try_get({:?})?,\n",
            column.name, column.name
        ));
    }
    row.push('}');
    Ok(row)
}
fn format_source(source: String) -> Result<String, GenerateError> {
    let mut formatter = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()?;
    formatter
        .stdin
        .take()
        .ok_or_else(|| GenerateError::Formatter("missing stdin".into()))?
        .write_all(source.as_bytes())?;
    let result = formatter.wait_with_output()?;
    if !result.status.success() {
        return Err(GenerateError::Formatter(
            String::from_utf8_lossy(&result.stderr).into_owned(),
        ));
    }
    String::from_utf8(result.stdout).map_err(|error| GenerateError::Formatter(error.to_string()))
}
